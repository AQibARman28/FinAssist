/**
 * Multiply two bytes in GF(2^8) using the AES irreducible polynomial 0x11B.
 *
 * This is the "Russian peasant" or shift-and-XOR algorithm: walk the bits
 * of `b` from low to high; whenever a bit is set, XOR the running value of
 * `a` into the product; then double `a` (shift left by 1), reducing modulo
 * 0x11B whenever the shift would overflow 8 bits.
 *
 * Used only by mixColumns. Constants 2 and 3 cover all the multiplications
 * needed by encryption.
 */
function gmul(a, b) {
    let p = 0;
    for (let i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        const hi = a & 0x80;        // is the high bit set before doubling?
        a = (a << 1) & 0xff;        // double in GF(2^8) — i.e. shift left
        if (hi) a ^= 0x1b;          // reduction: x^8 = x^4+x^3+x+1, low byte = 0x1B
        b >>>= 1;
    }
    return p;
}

/**
 * SubBytes — substitute each of the 16 state bytes through the S-box.
 *
 * This is the only non-linear step in AES. Without it, AES would degenerate
 * to a system of linear equations over GF(2) and be trivially breakable.
 */
function subBytes(state) {
    for (let i = 0; i < 16; i++) {
        state[i] = S_BOX[state[i]];
    }
}

/**
 * ShiftRows — cyclically shift the rows of the 4x4 state matrix.
 *
 * The state is stored column-major in a 16-byte buffer:
 *
 *      column 0   column 1   column 2   column 3
 *   r0 state[0]   state[4]   state[8]   state[12]
 *   r1 state[1]   state[5]   state[9]   state[13]
 *   r2 state[2]   state[6]   state[10]  state[14]
 *   r3 state[3]   state[7]   state[11]  state[15]
 *
 * Row 0 stays put; row 1 rotates left by 1; row 2 by 2; row 3 by 3.
 * Together with MixColumns this provides the diffusion property — small
 * changes in one byte propagate to many bytes after a few rounds.
 */
function shiftRows(state) {
    // Row 1: left rotate by 1  →  [a,b,c,d] becomes [b,c,d,a]
    const t1 = state[1];
    state[1]  = state[5];
    state[5]  = state[9];
    state[9]  = state[13];
    state[13] = t1;

    // Row 2: left rotate by 2  →  [a,b,c,d] becomes [c,d,a,b]  (= two swaps)
    let t2 = state[2];  state[2]  = state[10]; state[10] = t2;
    t2     = state[6];  state[6]  = state[14]; state[14] = t2;

    // Row 3: left rotate by 3 (= right rotate by 1)
    const t3 = state[15];
    state[15] = state[11];
    state[11] = state[7];
    state[7]  = state[3];
    state[3]  = t3;
}

/**
 * MixColumns — multiply each column of the state by a fixed matrix in GF(2^8).
 *
 * For each column [s0, s1, s2, s3] the new column is:
 *
 *      [ 2 3 1 1 ] [ s0 ]
 *      [ 1 2 3 1 ] [ s1 ]
 *      [ 1 1 2 3 ] [ s2 ]
 *      [ 3 1 1 2 ] [ s3 ]
 *
 * The matrix coefficients are GF(2^8) field elements — multiplication is
 * done by `gmul`. This is the operation that mixes information *across*
 * rows; ShiftRows mixes across columns. Together they spread one input
 * byte's influence to all 16 output bytes after just two rounds.
 */
function mixColumns(state) {
    for (let c = 0; c < 4; c++) {
        const s0 = state[4 * c + 0];
        const s1 = state[4 * c + 1];
        const s2 = state[4 * c + 2];
        const s3 = state[4 * c + 3];

        state[4 * c + 0] = gmul(2, s0) ^ gmul(3, s1) ^ s2          ^ s3;
        state[4 * c + 1] = s0          ^ gmul(2, s1) ^ gmul(3, s2) ^ s3;
        state[4 * c + 2] = s0          ^ s1          ^ gmul(2, s2) ^ gmul(3, s3);
        state[4 * c + 3] = gmul(3, s0) ^ s1          ^ s2          ^ gmul(2, s3);
    }
}

/**
 * AddRoundKey — XOR the state with 16 bytes of the expanded key.
 *
 * The `round` argument selects which 16-byte slice of the expanded key to
 * use: round 0 uses bytes 0..15, round 1 uses 16..31, ..., round 14 uses
 * bytes 224..239. AES-256 has 14 rounds and 15 round keys (one before the
 * first round, one after each round).
 *
 * AddRoundKey is the *only* place where the key affects the state. Every
 * other step (SubBytes, ShiftRows, MixColumns) is keyless and the same
 * for every user — the entire security comes from the round keys.
 */
function addRoundKey(state, expandedKey, round) {
    const offset = round * 16;
    for (let i = 0; i < 16; i++) {
        state[i] ^= expandedKey[offset + i];
    }
}

/**
 * keyExpansion — expand a 32-byte key into a 240-byte round-key schedule.
 *
 * AES-256 derives 60 4-byte words (= 240 bytes = 15 round keys of 16 bytes)
 * from the 32-byte (= 8 word) input key. The first 8 words are the key
 * itself; each subsequent word `w[i]` is computed from `w[i-1]` and
 * `w[i-8]`, with two special cases:
 *
 *   - Every 8th word (i.e. i % 8 === 0): apply RotWord (cyclic byte
 *     rotation), then SubWord (S-box on each byte), then XOR the high
 *     byte with the next round constant.
 *   - Every 4th word offset by 4 (i % 8 === 4): SubWord only, no RotWord
 *     and no RCON.
 *
 * The "% 8 === 4" branch is unique to AES-256; AES-128 does not have it.
 */
function keyExpansion(key) {
    if (key.length !== 32) {
        throw new Error(`AES-256 keyExpansion: key must be 32 bytes (got ${key.length})`);
    }

    const N = 8;            // input key length in 32-bit words
    const TOTAL = 60;       // total words in the expanded key (15 round keys * 4 words)

    // Pack the 32 input bytes into eight big-endian 32-bit words.
    const w = new Array(TOTAL);
    for (let i = 0; i < N; i++) {
        w[i] = (
            (key[4 * i]     << 24) |
            (key[4 * i + 1] << 16) |
            (key[4 * i + 2] <<  8) |
             key[4 * i + 3]
        ) >>> 0;
    }

    for (let i = N; i < TOTAL; i++) {
        let temp = w[i - 1];

        if (i % N === 0) {
            // RotWord: rotate left by one byte.
            temp = ((temp << 8) | (temp >>> 24)) >>> 0;
            // SubWord: apply S-box to each byte.
            temp = (
                (S_BOX[(temp >>> 24) & 0xff] << 24) |
                (S_BOX[(temp >>> 16) & 0xff] << 16) |
                (S_BOX[(temp >>>  8) & 0xff] <<  8) |
                 S_BOX[ temp         & 0xff]
            ) >>> 0;
            // XOR the round constant into the high byte.
            // RCON is 0-indexed here; the round-key index uses (i / N - 1).
            temp = (temp ^ (RCON[(i / N) - 1] << 24)) >>> 0;
        } else if (i % N === 4) {
            // SubWord only — AES-256 specific extra mixing step.
            temp = (
                (S_BOX[(temp >>> 24) & 0xff] << 24) |
                (S_BOX[(temp >>> 16) & 0xff] << 16) |
                (S_BOX[(temp >>>  8) & 0xff] <<  8) |
                 S_BOX[ temp         & 0xff]
            ) >>> 0;
        }

        w[i] = (w[i - N] ^ temp) >>> 0;
    }

    // Serialize the 60 words back into a 240-byte buffer (big-endian).
    const expanded = Buffer.alloc(240);
    for (let i = 0; i < TOTAL; i++) {
        expanded.writeUInt32BE(w[i], i * 4);
    }
    return expanded;
}

/**
 * aesEncryptBlock — encrypt one 16-byte block under an expanded AES-256 key.
 *
 * The structure is:
 *   - AddRoundKey with round-key 0 (this is the only thing applied before
 *     the rounds proper)
 *   - 13 main rounds: SubBytes → ShiftRows → MixColumns → AddRoundKey(t)
 *   - 1 final round: SubBytes → ShiftRows → AddRoundKey(14)
 *     (the final round drops MixColumns, by design — it would not improve
 *     diffusion since the next AddRoundKey absorbs anything it could do)
 *
 * Returns a fresh 16-byte Buffer; does not mutate the input.
 */
function aesEncryptBlock(block, expandedKey) {
    if (block.length !== 16) {
        throw new Error(`aesEncryptBlock: block must be 16 bytes (got ${block.length})`);
    }

    // Make a working copy so the caller's input buffer stays untouched.
    const state = Buffer.from(block);

    addRoundKey(state, expandedKey, 0);

    for (let round = 1; round < 14; round++) {
        subBytes(state);
        shiftRows(state);
        mixColumns(state);
        addRoundKey(state, expandedKey, round);
    }

    // Final round — note the absence of MixColumns.
    subBytes(state);
    shiftRows(state);
    addRoundKey(state, expandedKey, 14);

    return state;
}


