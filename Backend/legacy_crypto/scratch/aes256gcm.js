/**
 * ghashMultiply — multiply two 16-byte buffers as elements of GF(2^128) using
 * GCM's polynomial x^128 + x^7 + x^2 + x + 1 and GCM's bit ordering.
 *
 * Recall the bit-reversal convention: the leftmost bit of byte 0 of X is
 * the coefficient of x^0; the rightmost bit of byte 15 of X is the
 * coefficient of x^127.
 *
 * Algorithm: walk the bits of X from x^0 to x^127. Maintain a "shifted Y"
 * accumulator V that starts equal to Y and is multiplied by x after every
 * iteration. Whenever the current X bit is set, XOR V into the result Z.
 *
 * "Multiply V by x" is implemented as a *right* shift of the 128-bit buffer
 * (because of the bit-reversal convention), with the bit shifted out of
 * the LSB end triggering an XOR with 0xE1 in byte 0 to perform the
 * polynomial reduction.
 */
function ghashMultiply(X, Y) {
    const Z = Buffer.alloc(16);            // accumulator, starts at zero
    const V = Buffer.from(Y);              // running "Y * x^i", starts at Y

    for (let i = 0; i < 128; i++) {
        // Read bit i of X under GCM's convention:
        //   i=0 → byte 0, bit 7 (MSB)
        //   i=7 → byte 0, bit 0 (LSB)
        //   i=8 → byte 1, bit 7
        //   ...
        const xByte = i >>> 3;
        const xBit  = 7 - (i & 7);
        if ((X[xByte] >> xBit) & 1) {
            // Z ^= V
            for (let k = 0; k < 16; k++) Z[k] ^= V[k];
        }

        // V *= x  (right-shift the buffer by 1 bit, with reduction)
        const lsb = V[15] & 1;             // coefficient of x^127 before shift
        for (let k = 15; k > 0; k--) {
            V[k] = ((V[k] >>> 1) | ((V[k - 1] & 1) << 7)) & 0xff;
        }
        V[0] = (V[0] >>> 1) & 0xff;
        if (lsb) {
            // Reduction: bit fell off the high end → add x^128 mod P
            // = x^7 + x^2 + x + 1, which lives in byte 0 as 0xE1 in
            // GCM's bit-reversed encoding.
            V[0] ^= 0xe1;
        }
    }

    return Z;
}

/**
 * ghash — hash a sequence of 16-byte blocks under key H.
 *
 * Y starts at zero. For each block, XOR it into Y, then multiply Y by H.
 * The final Y is the hash. GCM uses this as a polynomial-evaluation hash:
 * if data is blocks B1, B2, ..., Bn, the result is
 *
 *      Y = B1·H^n + B2·H^(n-1) + ... + Bn·H   (in GF(2^128))
 *
 * `data` MUST already be a multiple of 16 bytes — pad it with zeros before
 * calling. We do this in the encrypt/decrypt routines via padToBlock.
 */
function ghash(H, data) {
    if (data.length % 16 !== 0) {
        throw new Error('ghash: data length must be a multiple of 16');
    }
    let Y = Buffer.alloc(16);              // accumulator starts at zero

    for (let offset = 0; offset < data.length; offset += 16) {
        // Y ^= block
        for (let k = 0; k < 16; k++) Y[k] ^= data[offset + k];
        // Y = Y * H   (in GF(2^128))
        Y = ghashMultiply(Y, H);
    }

    return Y;
}

/**
 * padToBlock — return a copy of `buf` zero-padded to the next 16-byte boundary.
 *
 * GCM's GHASH input format is "AAD padded || ciphertext padded || lengths".
 * Both the AAD and ciphertext sections must be a whole number of 16-byte
 * blocks; if either has a partial last block, the spec says to right-pad
 * with zeros up to the boundary.
 */
function padToBlock(buf) {
    const remainder = buf.length % 16;
    if (remainder === 0) return Buffer.from(buf);
    const padded = Buffer.alloc(buf.length + (16 - remainder));
    buf.copy(padded, 0);
    return padded;
}

/**
 * writeUInt64BE — write a non-negative integer as a 64-bit big-endian value.
 *
 * Buffer doesn't have a non-BigInt 64-bit BE writer, and BigInt is heavier
 * than we need. JavaScript numbers are exact up to 2^53, well above the
 * largest realistic message bit-length, so we just split into hi/lo halves.
 */
function writeUInt64BE(buf, offset, value) {
    const hi = Math.floor(value / 0x100000000);
    const lo = value >>> 0;
    buf.writeUInt32BE(hi, offset);
    buf.writeUInt32BE(lo, offset + 4);
}

/**
 * incrementCounter — increment the last 4 bytes of a 16-byte counter as a
 * big-endian 32-bit integer. The first 12 bytes (the IV portion) stay fixed.
 *
 * GCM uses this between successive blocks of the keystream: each block of
 * keystream is AES(counter), and the counter advances by 1 for the next
 * block. With a 32-bit counter we can encrypt up to 2^32 - 2 blocks under
 * one (key, IV) pair — about 64 GiB of data.
 */
function incrementCounter(counter) {
    const out = Buffer.from(counter);
    let carry = 1;
    for (let i = 15; i >= 12 && carry; i--) {
        const sum = out[i] + carry;
        out[i] = sum & 0xff;
        carry = sum >> 8;
    }
    return out;
}

/**
 * gctr — GCM counter mode encryption.
 *
 * Walk the input in 16-byte chunks. For each chunk:
 *   - encrypt the current counter to produce a 16-byte keystream block
 *   - XOR the keystream with the input chunk
 *   - increment the counter
 *
 * The last chunk may be shorter than 16 bytes; we use only as many keystream
 * bytes as we need. Decryption is the same operation (XOR is self-inverse).
 */
function gctr(expandedKey, initialCounter, input) {
    const output = Buffer.alloc(input.length);
    let counter = Buffer.from(initialCounter);

    let offset = 0;
    while (offset < input.length) {
        const keystream = aesEncryptBlock(counter, expandedKey);
        const blockLen  = Math.min(16, input.length - offset);
        for (let i = 0; i < blockLen; i++) {
            output[offset + i] = input[offset + i] ^ keystream[i];
        }
        counter = incrementCounter(counter);
        offset += blockLen;
    }

    return output;
}

/**
 * constantTimeEqual — XOR-and-OR comparison that does not short-circuit.
 *
 * For tag verification we cannot use Buffer.compare or === on hex strings:
 * those return as soon as they see the first different byte, which leaks
 * information about *where* the tag mismatched via timing. Walking every
 * byte with bitwise OR makes the comparison time depend only on length,
 * not on contents.
 */
function constantTimeEqual(a, b) {
    if (a.length !== b.length) return false;
    let diff = 0;
    for (let i = 0; i < a.length; i++) {
        diff |= a[i] ^ b[i];
    }
    return diff === 0;
}


