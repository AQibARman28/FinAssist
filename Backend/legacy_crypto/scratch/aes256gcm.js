/**
 * Coerce a string-or-Buffer into a Buffer (UTF-8 encoded for strings).
 * `null`/`undefined` are treated as empty input — handy for the optional
 * `aad` argument.
 */
function toBuffer(input, label) {
    if (input == null) return Buffer.alloc(0);
    if (Buffer.isBuffer(input)) return input;
    if (typeof input === 'string') return Buffer.from(input, 'utf8');
    throw new TypeError(`aes256gcm: ${label} must be a string, Buffer, or null/undefined`);
}

/**
 * Encrypt and authenticate `plaintext` under (`key`, `iv`), with optional
 * additional authenticated data `aad`.
 *
 * @param {Buffer}        key        — 32 bytes
 * @param {Buffer}        iv         — exactly 12 bytes (other lengths rejected)
 * @param {Buffer|string} plaintext  — any length, including 0
 * @param {Buffer|string} [aad]      — any length, including 0
 * @returns {{ciphertext: Buffer, tag: Buffer}} — ciphertext is same length as
 *           plaintext; tag is exactly 16 bytes
 */
function aes256gcmEncrypt(key, iv, plaintext, aad) {
    if (!Buffer.isBuffer(key) || key.length !== 32) {
        throw new Error('aes256gcmEncrypt: key must be a 32-byte Buffer');
    }
    if (!Buffer.isBuffer(iv) || iv.length !== 12) {
        throw new Error('aes256gcmEncrypt: iv must be a 12-byte Buffer (we restrict to the standard 12-byte IV path)');
    }

    const ptBuf  = toBuffer(plaintext, 'plaintext');
    const aadBuf = toBuffer(aad,       'aad');

    const expandedKey = keyExpansion(key);

    // Step 1: H = AES_K(0^128). H is the GHASH key.
    const H = aesEncryptBlock(Buffer.alloc(16), expandedKey);

    // Step 2: J0 = IV || 0x00000001    (12-byte IV path only)
    const J0 = Buffer.alloc(16);
    iv.copy(J0, 0);
    J0[15] = 0x01;

    // Step 3: encrypt with CTR starting at J0+1
    const initialCtr = incrementCounter(J0);
    const ciphertext = gctr(expandedKey, initialCtr, ptBuf);

    // Step 4: assemble the GHASH input
    //   AAD padded to next 16-byte boundary
    //   || ciphertext padded to next 16-byte boundary
    //   || (len(AAD) in bits as 64-bit BE) (len(CT) in bits as 64-bit BE)
    const lengthsBlock = Buffer.alloc(16);
    writeUInt64BE(lengthsBlock, 0, aadBuf.length     * 8);
    writeUInt64BE(lengthsBlock, 8, ciphertext.length * 8);

    const ghashInput = Buffer.concat([
        padToBlock(aadBuf),
        padToBlock(ciphertext),
        lengthsBlock
    ]);
    const S = ghash(H, ghashInput);

    // Step 5: tag = S XOR AES_K(J0)
    const J0Encrypted = aesEncryptBlock(J0, expandedKey);
    const tag = Buffer.alloc(16);
    for (let i = 0; i < 16; i++) tag[i] = S[i] ^ J0Encrypted[i];

    return { ciphertext, tag };
}

/**
 * Verify the authentication tag and (only on success) decrypt `ciphertext`
 * under (`key`, `iv`) with the same `aad` used at encrypt time.
 *
 * Throws 'GCM authentication failed' on any tag mismatch BEFORE any
 * plaintext is returned, so a caller cannot use this routine as a
 * decryption oracle.
 *
 * @param {Buffer}        key
 * @param {Buffer}        iv
 * @param {Buffer|string} ciphertext
 * @param {Buffer}        tag      — exactly 16 bytes
 * @param {Buffer|string} [aad]
 * @returns {Buffer} plaintext
 */
function aes256gcmDecrypt(key, iv, ciphertext, tag, aad) {
    if (!Buffer.isBuffer(key) || key.length !== 32) {
        throw new Error('aes256gcmDecrypt: key must be a 32-byte Buffer');
    }
    if (!Buffer.isBuffer(iv) || iv.length !== 12) {
        throw new Error('aes256gcmDecrypt: iv must be a 12-byte Buffer');
    }
    if (!Buffer.isBuffer(tag) || tag.length !== 16) {
        throw new Error('aes256gcmDecrypt: tag must be a 16-byte Buffer');
    }

    const ctBuf  = toBuffer(ciphertext, 'ciphertext');
    const aadBuf = toBuffer(aad,        'aad');

    const expandedKey = keyExpansion(key);

    // Reproduce H, J0, and the expected tag exactly as the encrypt side did.
    const H = aesEncryptBlock(Buffer.alloc(16), expandedKey);

    const J0 = Buffer.alloc(16);
    iv.copy(J0, 0);
    J0[15] = 0x01;

    const lengthsBlock = Buffer.alloc(16);
    writeUInt64BE(lengthsBlock, 0, aadBuf.length * 8);
    writeUInt64BE(lengthsBlock, 8, ctBuf.length  * 8);

    const ghashInput = Buffer.concat([
        padToBlock(aadBuf),
        padToBlock(ctBuf),
        lengthsBlock
    ]);
    const S = ghash(H, ghashInput);

    const J0Encrypted = aesEncryptBlock(J0, expandedKey);
    const expectedTag = Buffer.alloc(16);
    for (let i = 0; i < 16; i++) expectedTag[i] = S[i] ^ J0Encrypted[i];

    // Verify BEFORE producing plaintext — never expose the keystream to a
    // caller who supplied a bad tag.
    if (!constantTimeEqual(expectedTag, tag)) {
        throw new Error('GCM authentication failed');
    }

    // Tag is good — decrypt by running CTR mode again (same operation as encrypt).
    const initialCtr = incrementCounter(J0);
    return gctr(expandedKey, initialCtr, ctBuf);
}


module.exports = { aes256gcmEncrypt, aes256gcmDecrypt };


// ─────────────────────────────────────────────────────────────────────────────
// Self-test — runs only when this file is executed directly:
//   node aes256gcm.js
// Three NIST SP 800-38D appendix B test vectors. Each checks both the
// ciphertext and the authentication tag. All three should print PASS.
// We additionally round-trip every vector through aes256gcmDecrypt to
// confirm the decrypt path agrees with the encrypt path.
// ─────────────────────────────────────────────────────────────────────────────
if (require.main === module) {
    const vectors = [
        {
            name:        'NIST #1 (empty PT, empty AAD)',
            key:         Buffer.alloc(32),
            iv:          Buffer.alloc(12),
            plaintext:   Buffer.alloc(0),
            aad:         Buffer.alloc(0),
            expectedCt:  '',
            expectedTag: '530f8afbc74536b9a963b4f1c4cb738b'
        },
        {
            name:        'NIST #2 (16-byte zero PT, empty AAD)',
            key:         Buffer.alloc(32),
            iv:          Buffer.alloc(12),
            plaintext:   Buffer.alloc(16),
            aad:         Buffer.alloc(0),
            expectedCt:  'cea7403d4d606b6e074ec5d3baf39d18',
            expectedTag: 'd0d1c8a799996bf0265b98b5d48ab919'
        },
        {
            name:        'NIST #3 (60-byte PT + 20-byte AAD)',
            key:         Buffer.from('feffe9928665731c6d6a8f9467308308feffe9928665731c6d6a8f9467308308', 'hex'),
            iv:          Buffer.from('cafebabefacedbaddecaf888', 'hex'),
            plaintext:   Buffer.from(
                'd9313225f88406e5a55909c5aff5269a' +
                '86a7a9531534f7da2e4c303d8a318a72' +
                '1c3c0c95956809532fcf0e2449a6b525' +
                'b16aedf5aa0de657ba637b39',
                'hex'
            ),
            aad:         Buffer.from('feedfacedeadbeeffeedfacedeadbeefabaddad2', 'hex'),
            expectedCt:  '522dc1f099567d07f47f37a32a84427d' +
                         '643a8cdcbfe5c0c97598a2bd2555d1aa' +
                         '8cb08e48590dbb3da7b08b1056828838' +
                         'c5f61e6393ba7a0abcc9f662',
            expectedTag: '76fc6ece0f4e1768cddf8853bb2d551b'
        }
    ];

    let allPass = true;
    for (const v of vectors) {
        const { ciphertext, tag } = aes256gcmEncrypt(v.key, v.iv, v.plaintext, v.aad);
        const ctHex  = ciphertext.toString('hex');
        const tagHex = tag.toString('hex');
        const ctOk   = ctHex  === v.expectedCt;
        const tagOk  = tagHex === v.expectedTag;

        // Round-trip: decrypt should yield the original plaintext, and a tag
        // tampered by 1 byte must throw 'GCM authentication failed'.
        let roundTripOk = false;
        let rejectsBadTag = false;
        try {
            const decrypted = aes256gcmDecrypt(v.key, v.iv, ciphertext, tag, v.aad);
            roundTripOk = Buffer.compare(decrypted, v.plaintext) === 0;
        } catch { /* roundTripOk stays false */ }
        try {
            const badTag = Buffer.from(tag);
            badTag[0] ^= 0x01;
            aes256gcmDecrypt(v.key, v.iv, ciphertext, badTag, v.aad);
        } catch (err) {
            rejectsBadTag = err.message === 'GCM authentication failed';
        }

        const pass = ctOk && tagOk && roundTripOk && rejectsBadTag;
        if (!pass) allPass = false;

        console.log(`${pass ? 'PASS' : 'FAIL'}  ${v.name}`);
        if (!pass) {
            if (!ctOk) {
                console.log(`        ciphertext expected: ${v.expectedCt}`);
                console.log(`        ciphertext got:      ${ctHex}`);
            }
            if (!tagOk) {
                console.log(`        tag expected: ${v.expectedTag}`);
                console.log(`        tag got:      ${tagHex}`);
            }
            if (!roundTripOk)   console.log(`        decrypt round-trip did not recover plaintext`);
            if (!rejectsBadTag) console.log(`        decrypt did NOT reject a tampered tag — security failure`);
        }
    }

    process.exit(allPass ? 0 : 1);
}
