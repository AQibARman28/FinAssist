def _to_bytes(value, label):
    """Coerce a string-or-bytes input to bytes (UTF-8 encoded for strings).

    Used for plaintext, ciphertext (where allowed), and aad. `None` is
    treated as empty input — handy for the optional `aad` argument.
    """
    if value is None:
        return b''
    if isinstance(value, (bytes, bytearray)):
        return bytes(value)
    if isinstance(value, str):
        return value.encode('utf-8')
    raise TypeError(f"aes256_gcm: {label} must be str, bytes, bytearray, or None")


def aes256_gcm_encrypt(key, iv, plaintext, aad=b''):
    """Encrypt and authenticate `plaintext` under (`key`, `iv`), with optional
    additional authenticated data `aad`.

    Args:
        key:       32 bytes (bytes or bytearray)
        iv:        exactly 12 bytes (other lengths rejected)
        plaintext: any length, including 0; bytes, bytearray, or str
        aad:       any length, including 0; bytes, bytearray, str, or None

    Returns:
        (ciphertext, tag) — ciphertext is same length as plaintext;
        tag is exactly 16 bytes.
    """
    if not isinstance(key, (bytes, bytearray)) or len(key) != 32:
        raise ValueError("aes256_gcm_encrypt: key must be 32 bytes (bytes or bytearray)")
    if not isinstance(iv, (bytes, bytearray)) or len(iv) != 12:
        raise ValueError(
            "aes256_gcm_encrypt: iv must be exactly 12 bytes (we restrict to "
            "the standard 12-byte IV path; other lengths are rejected)"
        )

    pt_buf  = _to_bytes(plaintext, 'plaintext')
    aad_buf = _to_bytes(aad,       'aad')

    expanded_key = _key_expansion(bytes(key))

    # Step 1: H = AES_K(0^128). H is the GHASH key.
    h = _aes_encrypt_block(bytes(16), expanded_key)

    # Step 2: J0 = IV || 0x00000001    (12-byte IV path only)
    j0 = bytes(iv) + b'\x00\x00\x00\x01'

    # Step 3: encrypt with CTR starting at J0 + 1
    initial_ctr = _increment_counter(j0)
    ciphertext  = _gctr(expanded_key, initial_ctr, pt_buf)

    # Step 4: assemble the GHASH input
    #   AAD padded to next 16-byte boundary
    #   || ciphertext padded to next 16-byte boundary
    #   || (len(AAD) in bits as 64-bit BE) (len(CT) in bits as 64-bit BE)
    lengths_block = (
        (len(aad_buf)    * 8).to_bytes(8, 'big') +
        (len(ciphertext) * 8).to_bytes(8, 'big')
    )
    ghash_input = _pad_to_block(aad_buf) + _pad_to_block(ciphertext) + lengths_block
    s = _ghash(h, ghash_input)

    # Step 5: tag = S XOR AES_K(J0)
    j0_encrypted = _aes_encrypt_block(j0, expanded_key)
    tag = bytes(a ^ b for a, b in zip(s, j0_encrypted))

    return ciphertext, tag


def aes256_gcm_decrypt(key, iv, ciphertext, tag, aad=b''):
    """Verify the authentication tag and (only on success) decrypt
    `ciphertext` under (`key`, `iv`) with the same `aad` used at encrypt
    time.

    Raises GCMAuthenticationError on any tag mismatch BEFORE any
    plaintext is returned, so a caller cannot use this routine as a
    decryption oracle.
    """
    if not isinstance(key, (bytes, bytearray)) or len(key) != 32:
        raise ValueError("aes256_gcm_decrypt: key must be 32 bytes (bytes or bytearray)")
    if not isinstance(iv, (bytes, bytearray)) or len(iv) != 12:
        raise ValueError("aes256_gcm_decrypt: iv must be exactly 12 bytes")
    if not isinstance(tag, (bytes, bytearray)) or len(tag) != 16:
        raise ValueError("aes256_gcm_decrypt: tag must be exactly 16 bytes")

    if not isinstance(ciphertext, (bytes, bytearray)):
        raise TypeError("aes256_gcm_decrypt: ciphertext must be bytes or bytearray")
    ct_buf  = bytes(ciphertext)
    aad_buf = _to_bytes(aad, 'aad')

    expanded_key = _key_expansion(bytes(key))

    # Reproduce H, J0, and the expected tag exactly as the encrypt side did.
    h  = _aes_encrypt_block(bytes(16), expanded_key)
    j0 = bytes(iv) + b'\x00\x00\x00\x01'

    lengths_block = (
        (len(aad_buf) * 8).to_bytes(8, 'big') +
        (len(ct_buf)  * 8).to_bytes(8, 'big')
    )
    ghash_input = _pad_to_block(aad_buf) + _pad_to_block(ct_buf) + lengths_block
    s = _ghash(h, ghash_input)

    j0_encrypted = _aes_encrypt_block(j0, expanded_key)
    expected_tag = bytes(a ^ b for a, b in zip(s, j0_encrypted))

    # Verify BEFORE producing plaintext — never expose the keystream to a
    # caller who supplied a bad tag.
    if not _constant_time_equal(expected_tag, bytes(tag)):
        raise GCMAuthenticationError("GCM authentication failed")

    # Tag is good — decrypt by running CTR mode again (same operation as encrypt).
    initial_ctr = _increment_counter(j0)
    return _gctr(expanded_key, initial_ctr, ct_buf)


