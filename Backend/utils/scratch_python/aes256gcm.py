# _RCON — round constants used by the AES-256 key schedule.
#
# Each value is the high byte of a 4-byte word; the other three bytes are 0.
# The values are powers of x in GF(2^8): RCON[i] = x^(i+1) reduced by the
# AES polynomial. AES-256 needs only 7 entries because the key schedule
# applies a round constant once every 8 words, and there are 60 words in
# the expanded key (60 = 8 + 7*8 + 4 leftover).
_RCON = (0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40)


