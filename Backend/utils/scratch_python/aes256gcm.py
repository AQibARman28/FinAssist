"""
AES-256-GCM implemented from scratch.

This file is a direct port of Backend/utils/scratch/aes256gcm.js — same
S-box, same RCON, same 14-round structure, same 12-byte-IV restriction,
same GHASH polynomial.

The big picture
─────────────────────────────────────────────────────────────────────────────
This file does two distinct things stacked on top of each other:

  1. AES-256 (FIPS PUB 197) — a *block cipher*. Given a 32-byte key and a
     16-byte input block, it produces a 16-byte output block, deterministic
     and reversible. AES on its own only knows how to mangle one block at
     a time. It cannot encrypt a 17-byte file, it cannot detect tampering,
     and it cannot use the same key safely on two different messages.

  2. GCM (NIST SP 800-38D) — a *mode of operation* that wraps a block
     cipher to give you (a) confidentiality of arbitrary-length data and
     (b) authenticity (a tag that detects any tampering, including changes
     to "associated data" that is sent alongside but not encrypted).

Why GCM instead of "encrypt-then-MAC"
─────────────────────────────────────────────────────────────────────────────
The traditional way to get authenticated encryption is to encrypt with one
key and MAC with another (e.g., AES-CBC + HMAC-SHA256). GCM bundles both
jobs into a single pass over the data using only AES — no separate hash
function and no second key. It is faster on modern CPUs and has a clean
security proof.

GCM is built from two ingredients:
  - CTR mode for confidentiality. We turn AES into a stream cipher by
    encrypting an incrementing counter and XORing the result with the
    plaintext. Decryption is the same operation (XOR is self-inverse), so
    we never call AES decryption.
  - GHASH for authenticity. We compute a polynomial hash over the AAD,
    the ciphertext, and the lengths, in a finite field of 2^128 elements.
    The hash is "keyed" by H = AES(zero block), and its output is XORed
    with one more AES output to produce the final 16-byte authentication
    tag.

IV length policy
─────────────────────────────────────────────────────────────────────────────
The GCM spec allows arbitrary IV lengths via a GHASH-derived J0. In
practice every real-world GCM deployment uses a 12-byte IV, because the
12-byte branch has a simple closed form: J0 = IV || 0x00000001. We hard
reject any other length to keep the code simple and to discourage caller
mistakes.

The GCM bit-reversal gotcha
─────────────────────────────────────────────────────────────────────────────
GCM's GF(2^128) numbers the bits of a 16-byte buffer "backwards". The
leftmost (high-order) bit of byte 0 is treated as the lowest-degree
coefficient (x^0), and the rightmost (low-order) bit of byte 15 is the
highest-degree coefficient (x^127). This is the opposite of how every
other "treat a buffer as a big number" convention works.

The practical consequence: "multiply by x" in GF(2^128) — which
mathematically shifts coefficients up by one degree — looks like a
*right* shift of the byte buffer, with reduction by the magic value 0xE1
(the bit-reversal of 0x87, the natural form of the AES polynomial). If
you write GHASH using the "obvious" left-shift convention you get a
function that produces the wrong answer on every input. This is the
single most common GCM implementation bug.

Allowed dependencies
─────────────────────────────────────────────────────────────────────────────
Zero. AES-GCM is self-contained — no imports for the algorithm itself.
The optional cross-check at the bottom imports `cryptography` purely as a
reference; clearly marked.
"""


