#  PART B — GCM mode (NIST SP 800-38D)
# ═════════════════════════════════════════════════════════════════════════════


def _ghash_multiply(x, y):
    """Multiply two 16-byte buffers as elements of GF(2^128) using GCM's
    polynomial x^128 + x^7 + x^2 + x + 1 and GCM's bit ordering.

    Recall the bit-reversal convention: the leftmost bit of byte 0 of X
    is the coefficient of x^0; the rightmost bit of byte 15 of X is the
    coefficient of x^127.

    Algorithm: walk the bits of X from x^0 to x^127. Maintain a "shifted Y"
    accumulator V that starts equal to Y and is multiplied by x after every
    iteration. Whenever the current X bit is set, XOR V into the result Z.

    "Multiply V by x" is implemented as a *right* shift of the 128-bit
    buffer (because of the bit-reversal convention), with the bit shifted
    out of the LSB end triggering an XOR with 0xE1 in byte 0 to perform
    the polynomial reduction.
    """
    z = bytearray(16)                   # accumulator, starts at zero
    v = bytearray(y)                    # running "Y * x^i", starts at Y

    for i in range(128):
        # Read bit i of X under GCM's convention:
        #   i=0 → byte 0, bit 7 (MSB)
        #   i=7 → byte 0, bit 0 (LSB)
        #   i=8 → byte 1, bit 7
        #   ...
        x_byte = i >> 3
        x_bit  = 7 - (i & 7)
        if (x[x_byte] >> x_bit) & 1:
            # Z ^= V
            for k in range(16):
                z[k] ^= v[k]

        # V *= x  (right-shift the buffer by 1 bit, with reduction)
        lsb = v[15] & 1                 # coefficient of x^127 before shift
        for k in range(15, 0, -1):
            v[k] = ((v[k] >> 1) | ((v[k - 1] & 1) << 7)) & 0xff
        v[0] = (v[0] >> 1) & 0xff
        if lsb:
            # Reduction: bit fell off the high end → add x^128 mod P
            # = x^7 + x^2 + x + 1, which lives in byte 0 as 0xE1 in
            # GCM's bit-reversed encoding.
            v[0] ^= 0xe1

    return bytes(z)


def _ghash(h, data):
    """Hash a sequence of 16-byte blocks under key H.

    Y starts at zero. For each block, XOR it into Y, then multiply Y by H.
    The final Y is the hash.

    `data` MUST already be a multiple of 16 bytes — pad it with zeros
    before calling. We do this in the encrypt/decrypt routines via
    _pad_to_block.
    """
    if len(data) % 16 != 0:
        raise ValueError(f"_ghash: data length must be a multiple of 16 (got {len(data)})")

    y = bytearray(16)                   # accumulator starts at zero

    for offset in range(0, len(data), 16):
        # Y ^= block
        for k in range(16):
            y[k] ^= data[offset + k]
        # Y = Y * H  (in GF(2^128))
        y = bytearray(_ghash_multiply(h, y))

    return bytes(y)


def _pad_to_block(buf):
    """Return a copy of `buf` zero-padded to the next 16-byte boundary.

    GCM's GHASH input format is "AAD padded || ciphertext padded || lengths".
    Both the AAD and ciphertext sections must be a whole number of 16-byte
    blocks; if either has a partial last block, the spec says to right-pad
    with zeros up to the boundary.
    """
    remainder = len(buf) % 16
    if remainder == 0:
        return bytes(buf)
    return bytes(buf) + b'\x00' * (16 - remainder)


def _increment_counter(counter):
    """Increment the last 4 bytes of a 16-byte counter as a big-endian
    32-bit integer. The first 12 bytes (the IV portion) stay fixed.

    GCM uses this between successive blocks of the keystream: each block
    of keystream is AES(counter), and the counter advances by 1 for the
    next block. With a 32-bit counter we can encrypt up to 2^32 - 2 blocks
    under one (key, IV) pair — about 64 GiB of data.
    """
    high = counter[:12]
    low_int = int.from_bytes(counter[12:], 'big')
    low_int = (low_int + 1) & 0xFFFFFFFF
    return bytes(high) + low_int.to_bytes(4, 'big')


def _gctr(expanded_key, initial_counter, input_buf):
    """GCM counter mode encryption.

    Walk the input in 16-byte chunks. For each chunk:
      - encrypt the current counter to produce a 16-byte keystream block
      - XOR the keystream with the input chunk
      - increment the counter

    The last chunk may be shorter than 16 bytes; we use only as many
    keystream bytes as we need. Decryption is the same operation
    (XOR is self-inverse).
    """
    output  = bytearray(len(input_buf))
    counter = initial_counter

    offset = 0
    while offset < len(input_buf):
        keystream = _aes_encrypt_block(counter, expanded_key)
        block_len = min(16, len(input_buf) - offset)
        for i in range(block_len):
            output[offset + i] = input_buf[offset + i] ^ keystream[i]
        counter = _increment_counter(counter)
        offset += block_len

    return bytes(output)


def _constant_time_equal(a, b):
    """XOR-and-OR comparison that does not short-circuit.

    For tag verification we cannot use plain `==`: that returns as soon
    as it sees the first different byte, which leaks information about
    *where* the tag mismatched via timing. Walking every byte with
    bitwise OR makes the comparison time depend only on length, not on
    contents.
    """
    if len(a) != len(b):
        return False
    diff = 0
    for x, y in zip(a, b):
        diff |= x ^ y
    return diff == 0


